/** ช่วงน้ำหนักที่โชว์ในเกม (คิดโบนัสดูแล + ตัวกระจายแล้ว) */
export function displayRange(crop) {
  return {
    lo: crop.wMin * care.min * spread.lo,
    hi: crop.wMax * care.max * spread.hi,
    giantMax: crop.giant * care.max * spread.hi,
  };
}

/** น้ำหนักที่ได้จริงเมื่อติดชั้นโบนัสหางยาว */
export function megaWeight(crop, m) {
  const lo = crop.wMin * care.min;
  const hi = crop.wMax * care.max;
  return { lo: lo + (hi - lo) * m.rLo, hi: lo + (hi - lo) * m.rHi };
}

