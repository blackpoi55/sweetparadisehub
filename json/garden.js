const GOLD_BOOST = 2.5; // rareBoost ของปุ๋ยทอง — คูณเฉพาะพันธุ์ที่ mult > 1

/** โอกาสออกของแต่ละสายพันธุ์ (%) ตามเงื่อนไข */
export function variantOdds({ night = false, goldFert = false } = {}) {
  const list = variants.filter((v) => !(v.nightOnly && !night));
  const weighted = list.map((v) => ({
    v,
    w: v.w * (goldFert && v.mult > 1 ? GOLD_BOOST : 1),
  }));
  const total = weighted.reduce((s, e) => s + e.w, 0);
  return weighted.map((e) => ({ ...e.v, pct: (e.w / total) * 100 }));
}

